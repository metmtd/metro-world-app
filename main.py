# Функция для поиска города с наибольшей протяженностью метро в стране
def get_longest_metro_city(country):
    """
    Находит город с самой большой протяженностью метро в выбранной стране
    
    Args:
        country (str): Название страны
    
    Returns:
        dict: Информация о городе с наибольшей протяженностью метро
    """
    cities = metro_data[country]  # Получаем список городов страны
    # Находим город с максимальной протяженностью
    longest_city = max(cities, key=lambda x: x["протяженность"])
    return longest_city

# Функция для создания карты города
def create_city_map(city_info):
    """
    Создает интерактивную карту города
    
    Args:
        city_info (dict): Информация о городе
    
    Returns:
        folium.Map: Объект карты Folium
    """
    # Создаем карту с центром в координатах города
    city_map = folium.Map(
        location=city_info["координаты"],  # Координаты центра карты
        zoom_start=11,                     # Начальный уровень масштабирования
        tiles='OpenStreetMap'              # Тип карты
    )
    
    # Добавляем маркер на карту
    folium.Marker(
        city_info["координаты"],           # Координаты маркера
        popup=f"{city_info['город']}",     # Текст всплывающего окна
        tooltip=f"Метро {city_info['город']}"  # Текст подсказки при наведении
    ).add_to(city_map)
    
    return city_map

